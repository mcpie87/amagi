const FINAL = [
  'Klient mozna usunac z listy i ze szczegolow.',
  '',
  '### Conclusion',
  '',
  '- `a.txt`: nowa tresc',
  '',
  '### Commit message',
  '',
  '```text',
  '[WEWAI-6040] Usuwanie klienta',
  '',
  '- a.txt: nowa tresc',
  '```',
  '',
  'Verdict: review',
].join('\n')

const EMPTY_COMMIT_BODY = FINAL.replace('- a.txt: nowa tresc\n```', '```')

class FakeHarness implements Harness {
  readonly kind = 'fake'
  readonly prompts: string[] = []
  effect: (cwd: string) => void = () => {}

  constructor(private readonly summary: string) {}

  start(opts: AgentStartOptions): AgentProcess {
    this.prompts.push(opts.prompt)
    this.effect(opts.cwd)
    const queue = new AsyncQueue<AgentEvent>()
    queue.close()
    const outcome: AgentOutcome = {
      exitCode: 0,
      ok: true,
      sessionId: 'sess-2',
      summary: this.summary,
      usage: null,
      stderr: '',
    }
    return {
      pid: -1,
      events: () => queue,
      done: Promise.resolve(outcome),
      kill: async () => {},
      model: null,
      effort: null,
    }
  }
  resume(_sessionId: string, opts: AgentStartOptions): AgentProcess {
    return this.start(opts)
  }
  async listModels(): Promise<string[]> {
    return []
  }
  async listEfforts(): Promise<string[]> {
    return []
  }
}

const ISSUE: TrackerTask = {
  id: 'en-1',
  title: 'Brak mozliwosci usuniecia klienta',
  description: 'Umozliwic usuniecie klienta.',
  status: 'in_progress',
  priority: 2,
  type: 'feature',
  url: null,
  labels: ['WEWAI-6040'],
}

const tracker = {
  capabilities: { create: false, edit: false, dependencies: false },
  get: async () => ISSUE,
} as unknown as Tracker

const OLD_BODY = [
  '## ✨ old',
  '',
  '### 🧠 Conclusion',
  '',
  'English conclusion.',
  '',
  '### 🔎 Review',
  '',
  'Review rounds: 1.',
  '',
  '---',
  '',
  '<sub>Generated by amagi · claude</sub>',
].join('\n')

let dir: string
let wt: string
let store: Store
let updates: { title: string; body: string }[]
let forge: PrDriver

const git = (cwd: string, args: string[]) => execOk(exec, ['git', ...args], { cwd })

beforeEach(async () => {
  dir = mkdtempSync(join(tmpdir(), 'amagi-redo-'))
  const remote = join(dir, 'remote.git')
  const repo = join(dir, 'repo')
  wt = join(dir, 'wt')
  await execOk(exec, ['git', 'init', '-q', '--bare', '-b', 'main', remote])
  await execOk(exec, ['git', 'init', '-q', '-b', 'main', repo])
  await git(repo, ['config', 'user.email', 'a@example.invalid'])
  await git(repo, ['config', 'user.name', 'a'])
  writeFileSync(join(repo, 'a.txt'), 'base\n')
  await git(repo, ['add', '-A'])
  await git(repo, ['commit', '-q', '-m', 'base'])
  await git(repo, ['remote', 'add', 'origin', remote])
  await git(repo, ['push', '-q', 'origin', 'main'])
  await git(repo, ['worktree', 'add', '-q', '-b', 'amagi/en-1', wt, 'main'])
  for (const content of ['one\n', 'two\n']) {
    writeFileSync(join(wt, 'a.txt'), content)
    await git(wt, ['commit', '-q', '-am', `[en-1] ${content.trim()}`])
  }
  await git(wt, ['push', '-q', 'origin', 'amagi/en-1'])

  store = new Store(openDatabase(':memory:'))
  store.append('en-1', { type: 'task.claimed', title: ISSUE.title, tracker: 'beads' })
  store.append('en-1', { type: 'worktree.created', path: wt, branch: 'amagi/en-1' })
  store.append('en-1', { type: 'pr.created', url: 'https://forge.invalid/pr/7', number: 7 })
  for (const [from, to] of [
    ['claimed', 'worktree_ready'],
    ['worktree_ready', 'checks'],
    ['checks', 'committed'],
    ['committed', 'pr_open'],
  ] as const) {
    store.append('en-1', { type: 'task.state', from, to })
  }

  updates = []
  forge = {
    getPrBody: async () => OLD_BODY,
    updatePr: async (_cwd: string, _number: number, update: { title: string; body: string }) => {
      updates.push(update)
    },
  } as unknown as PrDriver
})

afterEach(() => {
  rmSync(dir, { recursive: true, force: true })
})

const deps = (harness: Harness) => ({
  store,
  tracker,
  harness,
  config: Config.parse({}),
  forge,
  repoRoot: join(dir, 'repo'),
})

describe('redoPr', () => {
  test('squashes the branch under the agent message, force-pushes it and rewrites the PR', async () => {
    await redoPr(deps(new FakeHarness(FINAL)), 'en-1')

    const log = await git(wt, ['log', '--format=%B%x00', 'origin/main..HEAD'])
    const messages = log.split('\0').filter((m) => m.trim() !== '')
    expect(messages).toHaveLength(1)
    expect(messages[0]?.trim()).toStartWith('[WEWAI-6040] Usuwanie klienta\n\n- a.txt: nowa tresc')
    const remoteHead = await git(wt, ['ls-remote', 'origin', 'refs/heads/amagi/en-1'])
    expect(remoteHead.split('\t')[0]).toBe((await git(wt, ['rev-parse', 'HEAD'])).trim())

    expect(updates).toHaveLength(1)
    expect(updates[0]?.title).toBe('[WEWAI-6040] Brak mozliwosci usuniecia klienta')
    expect(updates[0]?.body).toContain('`a.txt`: nowa tresc')
    expect(updates[0]?.body).not.toContain('English conclusion.')
    expect(updates[0]?.body).toContain('### 🔎 Review\n\nReview rounds: 1.')
  })

  test('rejects an agent commit message with an empty body instead of inventing one', async () => {
    const before = (await git(wt, ['rev-parse', 'HEAD'])).trim()

    await expect(redoPr(deps(new FakeHarness(EMPTY_COMMIT_BODY)), 'en-1')).rejects.toThrow(
      'malformed commit message: body must summarize the change',
    )

    expect((await git(wt, ['rev-parse', 'HEAD'])).trim()).toBe(before)
    expect(updates).toHaveLength(0)
  })

  test('uploads the demo clips still on disk and keeps them in the rewritten description', async () => {
    const previous = process.env.AMAGI_DEV_HOME
    process.env.AMAGI_DEV_HOME = join(dir, 'home')
    try {
      const demoDir = join(runStateDir('en-1'), 'demo')
      mkdirSync(demoDir, { recursive: true })
      writeFileSync(join(demoDir, '01-client-delete.webm'), 'video')
      store.append('en-1', {
        type: 'demo.recorded',
        clips: [{ name: '01-client-delete.webm', url: null }],
      })
      const uploaded: string[] = []
      Object.assign(forge, {
        uploadFile: async (_cwd: string, path: string) => {
          uploaded.push(path)
          return 'https://forge.invalid/uploads/clip.webm'
        },
      })

      await redoPr(deps(new FakeHarness(FINAL)), 'en-1')

      expect(uploaded).toEqual([join(demoDir, '01-client-delete.webm')])
      expect(updates[0]?.body).toContain(
        '![01-client-delete.webm](https://forge.invalid/uploads/clip.webm)',
      )
      expect(store.task('en-1')?.demo).toEqual([
        { name: '01-client-delete.webm', url: 'https://forge.invalid/uploads/clip.webm' },
      ])
    } finally {
      if (previous === undefined) delete process.env.AMAGI_DEV_HOME
      else process.env.AMAGI_DEV_HOME = previous
    }
  })

  test('leaves the branch and PR alone when the agent edits the worktree', async () => {
    const harness = new FakeHarness(FINAL)
    harness.effect = (cwd) => writeFileSync(join(cwd, 'a.txt'), 'edited\n')
    const before = (await git(wt, ['rev-parse', 'HEAD'])).trim()

    await expect(redoPr(deps(harness), 'en-1')).rejects.toThrow('changed the worktree')
    expect((await git(wt, ['rev-parse', 'HEAD'])).trim()).toBe(before)
    expect(updates).toHaveLength(0)
  })

  test('fails without rewriting when the agent writes no commit message', async () => {
    await expect(redoPr(deps(new FakeHarness('Summary only.')), 'en-1')).rejects.toThrow(
      'no `### Commit message`',
    )
    expect(updates).toHaveLength(0)
  })
})
