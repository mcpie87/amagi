export type RedoPrDeps = {
  store: Store
  tracker: Tracker
  harness: Harness
  config: Config
  forge: PrDriver
  repoRoot: string
  exec?: Exec
}

/** Task ids with a redo in flight, per repository store. */
const redoing = new WeakMap<Store, Set<string>>()

/** Whether a PR redo is rewriting this task's branch right now. */
export function prRedoInFlight(store: Store, taskId: string): boolean {
  return redoing.get(store)?.has(taskId) ?? false
}

/** The `### 🔎 Review` block of an amagi PR body, up to its footer; '' when it has none. */
function reviewBlock(body: string): string {
  const start = body.indexOf('\n### 🔎 Review')
  if (start === -1) return ''
  const footer = body.lastIndexOf('\n\n---\n\n<sub>Generated by amagi')
  return body.slice(start, footer > start ? footer : undefined).trimEnd()
}

/**
 * Uploads the demo clips in the task's demo directory that have no URL yet,
 * records the list when it changed and returns every uploaded clip for the PR
 * description. The directory holds the latest recording, so a clip recorded
 * before the projection tracked demos is picked up too. A failed upload stays
 * local and is retried by the next redo.
 */
async function uploadDemo(
  store: Store,
  forge: PrDriver,
  taskId: string,
  cwd: string,
): Promise<{ name: string; url: string }[]> {
  const dir = join(runStateDir(taskId), 'demo')
  const known = store.task(taskId)?.demo ?? []
  const names = existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => /\.(webm|mp4)$/i.test(name))
        .sort()
    : []
  const next: { name: string; url: string | null }[] = []
  for (const name of names) {
    const url = known.find((clip) => clip.name === name)?.url ?? null
    if (url === null && forge.uploadFile !== undefined) {
      try {
        next.push({ name, url: await forge.uploadFile(cwd, join(dir, name)) })
        continue
      } catch (err) {
        store.append(taskId, {
          type: 'error',
          message: `demo: uploading ${name}: ${errMsg(err)}`,
          fatal: false,
        })
      }
    }
    next.push({ name, url })
  }
  if (JSON.stringify(next) !== JSON.stringify(known)) {
    store.append(taskId, { type: 'demo.recorded', clips: next })
  }
  return next.flatMap(({ name, url }) => (url === null ? [] : [{ name, url }]))
}

/**
 * Rewrites an open PR's commit message, title and description over its
 * unchanged code: a fresh agent writes the final message again for the whole
 * diff, the branch is squashed into one commit with that message and
 * force-pushed, and the PR title and body are rebuilt. The review section of
 * the current body is kept, since no review runs here. Throws when the agent
 * writes no commit message or touches the worktree; the branch is left as it
 * was in both cases.
 */
export async function redoPr(deps: RedoPrDeps, taskId: string): Promise<void> {
  const busy = redoing.get(deps.store) ?? new Set<string>()
  redoing.set(deps.store, busy)
  if (busy.has(taskId)) throw new Error(`a redo of ${taskId} is already running`)
  busy.add(taskId)
  try {
    const task = deps.store.task(taskId)
    if (task === null) throw new Error(`unknown task ${taskId}`)
    const { worktree: cwd, branch, prNumber } = task
    if (cwd === null || branch === null || prNumber === null) {
      throw new Error(`task ${taskId} has no worktree, branch or pull request to redo`)
    }
    const { remote } = deps.config.forge
    await withPrWriteLock(deps.repoRoot, remote, branch, () =>
      rewrite(deps, taskId, cwd, branch, prNumber),
    )
  } finally {
    busy.delete(taskId)
  }
}

async function rewrite(
  deps: RedoPrDeps,
  taskId: string,
  cwd: string,
  branch: string,
  prNumber: number,
): Promise<void> {
  const { store, tracker, harness, config, forge } = deps
  const run = deps.exec ?? defaultExec
  const { remote, kind } = config.forge
  const base = config.repo.baseBranch

  // Anything uncommitted would be swept into the squashed commit.
  if ((await execOk(run, ['git', 'status', '--porcelain'], { cwd })).trim() !== '') {
    throw new Error(`worktree ${cwd} has uncommitted changes`)
  }
  const issue = await tracker.get(taskId)
  if (issue === null) throw new Error(`unknown task ${taskId}`)
  const auth = await gitTokenConfig(run, cwd, remote, forgeToken(kind, deps.repoRoot), kind)
  // A stale base ref would put base commits the branch merged into the squash.
  await execOk(run, ['git', 'fetch', remote, base], { cwd, env: auth })
  const head = (await execOk(run, ['git', 'rev-parse', 'HEAD'], { cwd })).trim()

  const ctx = {
    task: issue,
    worktree: cwd,
    branch,
    baseBranch: base,
    checks: configuredCheckCommands(config.checks),
  }
  const implement = config.harness.implement
  const proc = harness.start({
    cwd,
    prompt: rewriteFinalMessagePrompt(
      ctx,
      "The pull request for this task is open, but its commit message and description do not follow this repository's conventions.",
    ),
    systemPrompt: implementSystemPrompt(ctx),
    ...harnessStartOpts(implement),
    env: { AMAGI_WORKTREE: cwd, AMAGI_REPO_ROOT: deps.repoRoot },
  })
  const seat = implement.seat ?? harness.kind
  store.append(taskId, {
    type: 'agent.started',
    role: 'implement',
    harness: harness.kind,
    seat,
    model: proc.model ?? null,
    effort: proc.effort ?? null,
    cwd,
    resumed: false,
  })
  for await (const event of proc.events()) {
    if (event.kind === 'context') continue
    store.append(taskId, {
      type: 'agent.stream',
      role: 'implement',
      event: event.kind === 'usage' ? { ...event, seat } : event,
    })
  }
  const outcome = await proc.done
  store.append(taskId, {
    type: 'agent.exited',
    role: 'implement',
    exitCode: outcome.exitCode,
    sessionId: outcome.sessionId,
  })
  if (!outcome.ok) throw new Error(`agent failed: ${agentFailure(outcome)}`)
  const summary = outcome.summary

  const after = (await execOk(run, ['git', 'rev-parse', 'HEAD'], { cwd })).trim()
  const dirty = (await execOk(run, ['git', 'status', '--porcelain'], { cwd })).trim()
  if (after !== head || dirty !== '') {
    throw new Error('the agent changed the worktree; the branch was not rewritten')
  }
  const authored = agentCommitMessage(summary)
  if (authored === null) throw new Error('the agent wrote no `### Commit message` section')
  const meta = {
    harness: harness.kind,
    model: proc.model ?? implement.model ?? null,
    effort: proc.effort ?? implement.effort ?? null,
  }
  const message = withCommitFooter(authored, meta)
  const lint = lintCommitMessage(message)
  if (lint.length > 0) throw new Error(`malformed commit message: ${lint.join('; ')}`)

  const ref = await diffBase(run, cwd, remote, base)
  const mergeBase = (await execOk(run, ['git', 'merge-base', 'HEAD', ref], { cwd })).trim()
  await execOk(run, ['git', 'reset', '-q', '--soft', mergeBase], { cwd })
  const commit = await run(['git', 'commit', '-q', '-F', '-'], { cwd, stdin: message })
  if (commit.exitCode !== 0) {
    await run(['git', 'reset', '-q', '--soft', head], { cwd })
    throw new Error(`git commit failed: ${(commit.stderr || commit.stdout).trim()}`)
  }
  const sha = (await execOk(run, ['git', 'rev-parse', 'HEAD'], { cwd })).trim()
  await assertSafePushDestination(run, cwd, remote, branch, auth)
  // Pinned to the head this redo started from, so a push that landed meanwhile is not lost.
  await execOk(
    run,
    [
      'git',
      'push',
      `--force-with-lease=refs/heads/${branch}:${head}`,
      remote,
      `HEAD:refs/heads/${branch}`,
    ],
    { cwd, env: auth },
  )
  store.append(taskId, { type: 'commit.created', sha, subject: authored.split('\n')[0] ?? '' })

  let current = issue
  let prSummary = summary
  const sections = withAgentSections(issue.description, summary)
  if (sections !== null) {
    prSummary = sections.summary
    current = { ...issue, description: sections.description }
    if (tracker.capabilities.edit) {
      try {
        await tracker.updateTask(taskId, { description: sections.description })
      } catch (err) {
        store.append(taskId, {
          type: 'error',
          message: `writing the PR sections into ${taskId} failed: ${errMsg(err)}`,
          fatal: false,
        })
      }
    }
  }
  const changes = await changesSinceBase(run, cwd, remote, base)
  const demo = await uploadDemo(store, forge, taskId, cwd)
  const review = reviewBlock(await forge.getPrBody(cwd, prNumber))
  const body = `${formatPrBody(current, changes, undefined, prSummary, undefined, demo)}${review === '' ? '' : `\n${review}`}${modelFooter(meta.harness, meta.model, meta.effort)}`
  await forge.updatePr(cwd, prNumber, { title: prTitle(current), body })
}
